const healResultSchema = z.object({
  report: z
    .string()
    .describe(
      'Describe the original code quality, and issues you saw, and anything that needs tobe improved, or that is working well. Focus on robustness of the code for handling potentially varied pages within the target class of URLs, and also on correctness of the data returned.'
    ),
  rating: z
    .number()
    .min(1)
    .max(100)
    .describe(
      'An overall rating of the riginal code, where 100 is perfect, and 1 is completely unusable.'
    ),
  noChanges: z
    .boolean()
    .describe(
      'If true, the original code was corrected, and no changes are needed. If true, code should be null. If false, code should return different code than what you received. Generally, if the code is correctly handling pages, returning the proper format in a timely fashion, then no changes are needed. If is faulty, throwing errors, or returning inaccurate data where it could be returning proper data, then changes are needed. Do not request changes if the task is not possible to complete. Avoid endless loops of small refinements.'
    ),
});

export const healAgentOutputSchema = healResultSchema.extend({
  code: z.string().nullable(),
  confidence: z
    .number()
    .min(1)
    .max(100)
    .nullable()
    .describe(
      'If you wrote new code, give your confidence in it on a scale from 1 to 100, where 100 is the most confident.'
    ),
});

export const healStep = createStep({
  id: 'heal-step',
  inputSchema: z.object({
    botTemplate: z.instanceof(BotTemplate),
    code: z.string(),
  }),
  outputSchema: z.object({
    botTemplate: z.instanceof(BotTemplate),
    code: z.string(),
  }),
  execute: async ({ inputData, requestContext, mastra }) => {
    const context = requestContext.get('globalContext') as GlobalContext;
    const logger = context.logger;
    const agent = mastra!.getAgentById('writing-agent');

    const prompt = `You are evaluating out JavaScript functions. 

Base your evaluation on the function specifications below, using the relevant bot_ tools.

${renderBotTemplate(inputData.botTemplate)}

Use the bot_ tool(s) to test out the functions.
`;

    const { botTemplate, code } = inputData;
    let codeError: { code: string; message: string } | undefined;
    const bot = new Bot({
      name: 'heal-candidate',
      context,
      template: botTemplate,
    });
    try {
      await bot.setCode(code);
    } catch (e) {
      codeError = { code, message: errorString(e) };
      logger.warn(`Bot code was invalid: ${codeError.message}`);
    }

    const maxIterations = 3;
    let currentCode = code;
    for (let i = 0; i < maxIterations; i++) {
      const iteration = i + 1;
      logger.info(`Healing bot iteration ${iteration} of ${maxIterations}`);
      let codeErrorPrompt = '';
      if (codeError) {
        codeErrorPrompt = `
<previous-code-error>
The previous candidate code could not be compiled. Correct this error before evaluating or making further changes.

<error>
${codeError.message}
</error>

<code>
${codeError.code}
</code>
</previous-code-error>
`;
      }
      const resp = await agent.generate(`${prompt}${codeErrorPrompt}`, {
        structuredOutput: { schema: healAgentOutputSchema },
        maxSteps: 20,
        toolsets: { bot: bot.createTools('bot') },
      });
      const output = healAgentOutputSchema.parse(resp.object);
      logger.info(
        `Healing bot iteration ${iteration} result: rating=${output.rating}, confidence=${output.confidence}, noChanges=${output.noChanges}`
      );
      logger.debug(`Healing bot iteration ${iteration} code:\n${indentCode(output.code)}`);
      if (output.noChanges) {
        return { botTemplate, code: currentCode };
      }
      if (output.code === null) {
        throw new Error(`Healing bot iteration ${iteration} returned no code changes`);
      }

      const lastIteration = iteration === maxIterations;
      try {
        await bot.setCode(output.code);
        currentCode = output.code;
        codeError = undefined;
      } catch (e) {
        const message = errorString(e);
        if (lastIteration) {
          logger.warn(`Not using invalid code on last iteration: ${message}`);
        } else {
          codeError = { code: output.code, message };
          logger.warn(`Bot code was invalid: ${message}`);
          try {
            await bot.setCode(currentCode);
          } catch (e) {
            logger.warn(`Could not restore previous bot code: ${errorString(e)}`);
          }
        }
      }
      if (lastIteration) {
        logger.warn(`Healing bot exceeded ${maxIterations} retry attempts`);
      }
    }

    return { botTemplate, code: currentCode };
  },
});


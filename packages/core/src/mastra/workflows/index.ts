export const planStep = createStep({
  id: 'plan-step',
  inputSchema: z.object({
    botTemplate: z.instanceof(BotTemplate),
  }),
  outputSchema: z.object({
    botTemplate: z.instanceof(BotTemplate),
    plan: z.string(),
  }),

  execute: async ({ inputData, requestContext, mastra }) => {
    const context = requestContext.get('globalContext') as GlobalContext;
    const logger = context.logger;
    const prompt = `You are planning out JavaScript functions. Do not write code. Instead, generate a detailed report for how to write these functions. That report will be used by the next phase of the pipeline to write the code.

${renderBotTemplate(inputData.botTemplate)}

${guidelines}
`;

    const agent = mastra!.getAgentById('planning-agent');
    let resp = await agent.generate(prompt, {
      maxSteps: 30,
    });

    if (!resp.text.trim()) {
      logger.info(`No plan generated after max steps reached, do final no tool generation`);
      resp = await agent.generate(
        'Based on the research above, return the final implementation plan now.',
        {
          context: [
            { role: 'user', content: prompt },
            ...resp.steps.flatMap((step) => step.response.messages ?? []),
          ],
          maxSteps: 1,
          toolChoice: 'none',
        }
      );
    }

    const plan = resp.text;

    logger.debug(`Generated report: ${plan}`);
    logger.info(`Generated report: ${plan}`);

    return {
      botTemplate: inputData.botTemplate,
      plan,
    };
  },
});


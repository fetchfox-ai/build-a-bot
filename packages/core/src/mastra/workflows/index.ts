const renderBotTemplate = (botTemplate: BotTemplate) => {
  const tools = botTemplate.tools;
  let str = `
<available-context>You are running in a Javascript vm.Script(...), and have the following globals available: ${JSON.stringify(Object.keys(botTemplate.globals))}</available-context>
<available-context>You are running in a Javascript vm.Script(...), and have the following modules available: ${JSON.stringify(Object.keys(botTemplate.modules))}</available-context>
<available-tools>You are running in a Javascript vm.Script(...), and have the following tools available.

  You have helper functions available, based on the tools below. You can call any of these tools like this:

      const output = await tools.toolNameHere({ ...tool input here... });

  The tool name is its key in the mapping.

  For example, if a tool has the key "weatherTool", call it like this:

      const output = await tools.weatherTool({ city: "New York City, NY' });

  Tools:

  <tool-list>
    ${renderTools(tools)}
  </tool-list>
</available-tools>
<class-specs>`;
  for (const [classIdx, classSpec] of botTemplate.classSpecs.entries()) {
    const className =
      classSpec.numImplementations === 'many' ? classSpec.nameTemplate : classSpec.name;
    str += `
  <class-spec-#${classIdx + 1}>
    <num-implementations>${classSpec.numImplementations}</num-implementations>
    <${classSpec.numImplementations === 'many' ? 'name-template' : 'name'}>${className}</${classSpec.numImplementations === 'many' ? 'name-template' : 'name'}>
    <description>${classSpec.description}</description>
    <prompt>${classSpec.prompt}</prompt>
    <function-specs>`;
    for (const [functionIdx, functionSpec] of classSpec.functionSpecs.entries()) {
      str += `
      <function-spec-#${functionIdx + 1}>
        <name>${functionSpec.name}</name>
        <description>${functionSpec.description}</description>
        <prompt>${functionSpec.prompt}</prompt>
        <input-schema>${JSON.stringify(z.toJSONSchema(functionSpec.inputSchema))}</input-schema>
        <output-schema>${JSON.stringify(z.toJSONSchema(functionSpec.outputSchema))}</output-schema>
        <sample-inputs>${JSON.stringify(functionSpec.sampleInputs)}</sample-inputs>
      </function-spec-#${functionIdx + 1}>`;
    }
    str += `
    </function-specs>
  </class-spec-#${classIdx + 1}>`;
  }
  str += `
</class-specs>`;
  return str;
};

export const renderTools = (
  tools: Record<string, Pick<ToolAction<any, any>, 'description' | 'inputSchema' | 'outputSchema'>>
): string => {
  const schemaForPrompt = (schema: ToolAction<any, any>['inputSchema'], io: 'input' | 'output') => {
    if (schema === undefined) {
      return undefined;
    }

    const jsonSchema = standardSchemaToJSONSchema(toStandardSchema(schema), { io });
    return Object.fromEntries(Object.entries(jsonSchema).filter(([key]) => key !== '$schema'));
  };

  return JSON.stringify(
    Object.fromEntries(
      Object.entries(tools).map(([name, tool]) => [
        name,
        {
          description: tool.description,
          inputSchema: schemaForPrompt(tool.inputSchema, 'input'),
          outputSchema: schemaForPrompt(tool.outputSchema, 'output'),
        },
      ])
    ),
    null,
    2
  );
};

const guidelines = `# General guidelines

## Tool call guidelines

When completing tasks, use tools proactively and efficiently.

- You may make multiple tool calls in a single step when they are useful.
- If a task requires information from multiple sources, call the relevant tools in parallel rather than sequentially.
- Prefer batching independent tool calls together.
- After receiving tool results, evaluate whether additional tool calls are necessary.
- Avoid unnecessary tool calls; only call tools that materially contribute to the task.
- Do not call tools in parallel if they would conflict with one another, or if the subsequent tool calls depend on the results of the prior ones.
`;

const codingGuidelines = `# Guidelines

## Structure

Structure your code in the following way:

  export class FirstImpl {
    async someFunction(input) { /* return output matching outputSchema */ }
    async anotherFunction(input) { /* return output matching outputSchema */ }
  }

  // SecondImpl may use FirstImpl
  export class SecondImpl {
    async someFunction(input) { /* return output matching outputSchema */ }
    async anotherFunction(input) { /* return output matching outputSchema */ }
  }

For a single class specification, export exactly one class with its specified name. For a many class specification, export one or more classes whose names match its name template: replace * with a nonempty JavaScript-identifier suffix that describes the implementation, such as ExtractorListing and ExtractorDetail for Extractor*. Every required method must be a public instance method with its specified name. Classes can reuse each other, but dependencies must be non-cyclical. Describe this structure in the planning comments.

## Available modules

Do not import or require any modules. They are already in context. Only use specified, pre-loaded modules.

## Concurrency object

You have in your context a special object: \`pq\`. It is an instance of new PQueue() from https://github.com/sindresorhus/p-queue. It was instantiated like this:

  const pq = new PQueue({ concurrency: ...value... });

You should use this for limiting concurrency for fetch, browser instances, etc. The exact concurrency value has already been set, in accordance with proper rules like robots.txt. Therefore, you can simple make fetch tool calls, browser tool calls, etc. like this:

  const results = await Promise.all(
    urls.map(url => pq.add(() => tools.fetchTool({ url, proxy: '...' }))
  );

Generally, URLs should be handled concurrently.

Again, you do not need to create the pq object. It is already in the context.

## Comments

Before writing code, put in comments explaining the context, approach, implementation, and so on.

## Debug output

Generate helpful debug output sent to console.log()
`;
